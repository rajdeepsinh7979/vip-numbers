<script>
document.getElementById('contactForm').addEventListener('submit', async (e) => {
    e.preventDefault();
    const form = e.target;
    const btn = form.querySelector('button[type="submit"]');
    let status = form.querySelector('#contactFormStatus');

    if (!status) {
        status = document.createElement('p');
        status.id = 'contactFormStatus';
        status.style.marginTop = '12px';
        status.style.fontSize = '13px';
        form.appendChild(status);
    }

    // reCAPTCHA check (widget auto-fills a hidden 'g-recaptcha-response' field)
    const captchaResponse = grecaptcha.getResponse();
    if (!captchaResponse) {
        status.textContent = 'Please verify you are not a robot.';
        status.style.color = 'var(--red-accent)';
        return;
    }

    if (!btn) return;

    btn.disabled = true;
    const originalText = btn.innerHTML;
    btn.innerHTML = '<span class="iconify" data-icon="mdi:loading"></span> Sending...';
    status.textContent = '';

    try {
        const res = await fetch('api/send-message.php', {
            method: 'POST',
            body: new FormData(form)
        });
        const data = await res.json();

        status.textContent = data.message;
        status.style.color = data.success ? 'var(--green-accent)' : 'var(--red-accent)';

        if (data.success) form.reset();
    } catch (err) {
        status.textContent = 'Something went wrong. Please try again.';
        status.style.color = 'var(--red-accent)';
    } finally {
        btn.disabled = false;
        btn.innerHTML = originalText;
        grecaptcha.reset(); // reset widget whether success or fail
    }
});
</script>
