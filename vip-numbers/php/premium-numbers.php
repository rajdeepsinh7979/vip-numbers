        // Navbar scroll effect
        const navbar = document.querySelector('[data-js="navbar"]');
        window.addEventListener('scroll', () => {
            if (window.scrollY > 50) {
                navbar.classList.add('navbar--scrolled');
            } else {
                navbar.classList.remove('navbar--scrolled');
            }
        });

        // Mobile menu toggle
        const menuOpenBtn = document.querySelector('[data-js="menu-open"]');
        const menuCloseBtn = document.querySelector('[data-js="menu-close"]');
        const menuOverlay = document.querySelector('[data-js="menu-overlay"]');
        const body = document.body;

        if (menuOpenBtn) {
            menuOpenBtn.addEventListener('click', () => body.classList.add('menu-open'));
            menuCloseBtn.addEventListener('click', () => body.classList.remove('menu-open'));
            menuOverlay.addEventListener('click', () => body.classList.remove('menu-open'));
        }

        // Scroll reveal animation
        const revealObserver = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('revealed');
                    revealObserver.unobserve(entry.target);
                }
            });
        }, { threshold: 0.1 });

        // Observe any .reveal elements already in the page (call again for dynamically added ones)
        function observeReveals(root = document) {
            root.querySelectorAll('.reveal:not(.revealed)').forEach(el => revealObserver.observe(el));
        }
        observeReveals();
    </script>
    <script>
const grid = document.getElementById("numberGrid");

async function loadNumbers() {

    try {

        const response = await fetch("api/premium-numbers.php");

        if (!response.ok) {
            throw new Error(`Request failed with status ${response.status}`);
        }

        const data = await response.json();
        console.log(data);

        if (!data.success) {
            grid.innerHTML = "<p>Failed to load numbers.</p>";
            return;
        }

        if (data.numbers.length === 0) {
            grid.innerHTML = "<p>No numbers found.</p>";
            return;
        }

        grid.innerHTML = "";

        data.numbers.forEach(number => {

            const statusClass =
                number.status === "available"
                    ? "vip-card__status--available"
                    : "vip-card__status--sold";

            const statusIcon =
                number.status === "available"
                    ? "mdi:check-circle"
                    : "mdi:close-circle";

            const actionButton =
                number.status === "available"
                ? `
                    <a
                        href="https://wa.me/91YOURNUMBER?text=${encodeURIComponent('Hello, I am interested in VIP number ' + number.mobile_number)}"
                        target="_blank"
                        class="btn btn--whatsapp btn--sm"
                        style="flex:1;justify-content:center;"
                    >
                        <span class="iconify" data-icon="mdi:whatsapp"></span>
                        Buy
                    </a>
                `
                : `
                    <button class="btn btn--disabled btn--sm"
                        style="flex:1;justify-content:center;">
                        Sold Out
                    </button>
                `;

            const badge =
                number.category === "vip"
                    ? "VIP Choice"
                    : "Premium";

            grid.innerHTML += `
                <article class="number-card reveal">

                    <div class="number-card__inner">

                        <div class="number-card__top">

                            <span class="number-card__badge number-card__badge--gold">
                                ${badge}
                            </span>

                            <span class="vip-card__status ${statusClass}">
                                <span class="iconify" data-icon="${statusIcon}"></span>
                                ${number.status}
                            </span>

                        </div>

                        <div class="number-card__number-area">

                            <span class="number-card__prefix">+91</span>

                            <h3 class="number-card__number">
                                ${number.mobile_number}
                            </h3>

                            <span class="number-card__sum">
                                Sum = ${number.sum1} - ${number.sum2} - ${number.sum3}
                            </span>

                        </div>

                        <div class="number-card__divider"></div>

                        <div class="number-card__prices">

                            <div class="price-block--original">
                                <span class="price-original">
                                    ₹${Number(number.original_price).toLocaleString()}
                                </span>

                                <span class="discount-badge">
                                    ${number.discount}% OFF
                                </span>

                            </div>

                            <div class="price-block--selling">

                                <span class="price-selling">
                                    ₹${Number(number.selling_price).toLocaleString()}
                                </span>

                            </div>

                        </div>

                        <div class="number-card__actions">

                            ${actionButton}

                        </div>

                    </div>

                </article>
            `;
        });

        if (window.Iconify) {
            Iconify.scan();
        }

        // Newly injected cards carry the .reveal class but were added after
        // the initial observer pass — observe them now so they fade in too.
        observeReveals(grid);

    } catch (e) {

        console.error(e);
        grid.innerHTML = "<p>Unable to load numbers. Please try again later.</p>";

    }
}
loadNumbers();
