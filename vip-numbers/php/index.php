        document.addEventListener('DOMContentLoaded', () => {
            // Navbar Scroll & Mobile Menu
            const navbar = document.querySelector('[data-js="navbar"]');
            const menuOpen = document.querySelector('[data-js="menu-open"]');
            const menuClose = document.querySelector('[data-js="menu-close"]');
            const menuOverlay = document.querySelector('[data-js="menu-overlay"]');
            const body = document.body;
            const toggleMenu = () => body.classList.toggle('menu-open');
            if(menuOpen) menuOpen.addEventListener('click', toggleMenu);
            if(menuClose) menuClose.addEventListener('click', toggleMenu);
            if(menuOverlay) menuOverlay.addEventListener('click', toggleMenu);
            window.addEventListener('scroll', () => { if(navbar) navbar.classList.toggle('navbar--scrolled', window.scrollY > 50); });

            // FAQ Accordion
            document.querySelectorAll('[data-js="faq-toggle"]').forEach(btn => {
                btn.addEventListener('click', () => {
                    const item = btn.closest('.faq-item');
                    const isActive = item.classList.contains('faq-item--active');
                    // Close all
                    document.querySelectorAll('.faq-item').forEach(i => i.classList.remove('faq-item--active'));
                    // Open clicked if it wasn't active
                    if (!isActive) item.classList.add('faq-item--active');
                });
            });

            // Scroll Reveal
            const reveals = document.querySelectorAll('.reveal');
            const observer = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting) {
                        entry.target.classList.add('revealed');
                    }
                });
            }, { threshold: 0.1 });
            reveals.forEach(el => observer.observe(el));
        });
    </script>
